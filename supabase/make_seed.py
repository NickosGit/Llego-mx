"""Generate supabase/seed.sql — SIMULATED rides on Ruta 120, deterministic.

Run:  python3 supabase/make_seed.py
Every row has is_simulated = true and user_id = null.

Shape (laborable), anchored to Rodolfo's real baseline (1 Nov 2026):
  - leaving 04:45, the 120 leg takes ~45-50 min and he arrives 6:45-6:50 (Metro ~75 min)
  - the line grows and seats vanish after ~04:30
Demo target: usual 04:45 -> ~3 in 10 seated; 04:30 -> ~7 in 10 seated, still on time.
Sábado and domingo are deliberately thin (< 10 rides per slot) -> "Sin dato".
These numbers are invented to make the demo legible. They are NOT evidence.
"""
import random
from datetime import time
from pathlib import Path

random.seed(12)

# slot -> (typical wait, typical ride, share seated)
LABORABLE = {
    "04:00": (5, 33, 0.9), "04:15": (6, 33, 0.8), "04:30": (8, 33, 0.7),
    "04:45": (14, 34, 0.3), "05:00": (18, 35, 0.2), "05:15": (22, 37, 0.1),
    "05:30": (25, 39, 0.1), "05:45": (25, 41, 0.0), "06:00": (24, 43, 0.0),
    "06:15": (22, 44, 0.0), "06:30": (20, 44, 0.1),
}

rows = []

def add(day_type, slot, n, wait, ride, seat_share):
    n_bad = round(n * 0.3)               # ~3 in 10 rides are a bad day (longer line)
    n_seat = round(n * seat_share)
    for i in range(n):
        bad = i < n_bad
        w = max(0, wait + (random.randint(8, 12) if bad else random.randint(-3, 3)))
        r = ride + random.randint(-3, 3)
        seated = i >= n - n_seat         # seats go to non-bad-day rides first
        rows.append((day_type, slot, w, r, seated))

for slot, (w, r, s) in LABORABLE.items():
    add("laborable", slot, random.randint(12, 16), w, r, s)
for h, m in [(5, 0), (5, 30), (6, 0), (6, 30), (7, 0)]:
    add("sabado", f"{h:02d}:{m:02d}", random.randint(5, 8), 10, 32, 0.5)
for h, m in [(6, 0), (7, 0), (8, 0)]:
    add("domingo", f"{h:02d}:{m:02d}", random.randint(1, 4), 8, 30, 0.6)

lines = ["-- SIMULATED DATA. Generated by make_seed.py. Not real trips.",
         "delete from public.trips where is_simulated;",
         "insert into public.trips (day_type, depart_slot, wait_min, ride_min, seated, is_simulated) values"]
lines.append(",\n".join(
    f"('{d}','{s}',{w},{r},{'true' if st else 'false'},true)" for d, s, w, r, st in rows) + ";")
Path(__file__).with_name("seed.sql").write_text("\n".join(lines) + "\n")
print(f"{len(rows)} simulated rows written")
